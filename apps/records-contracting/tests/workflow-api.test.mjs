import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { once } from 'node:events';
import { createApp } from '../src/server.mjs';

test('new case, context, inventory, holds, tasks, and evidence corrections persist through the API', async t => {
  const directory = await mkdtemp(join(tmpdir(), 'va-workflow-api-'));
  const server = await createApp({ stateFile: join(directory, 'workspace.json') });
  server.listen(0, '127.0.0.1'); await once(server, 'listening');
  t.after(async () => { await new Promise(r => server.close(r)); await rm(directory, { recursive: true, force: true }); });
  const base = `http://127.0.0.1:${server.address().port}`;
  const post = async (path, body) => {
    const response = await fetch(`${base}${path}?asOf=2026-11-15`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(body) });
    return { status: response.status, body: await response.json() };
  };
  const note = 'Reviewed for the synthetic demo.';
  let result = await post('/api/cases', { title: 'Synthetic records acquisition', owner: 'Demo reviewer', note });
  assert.equal(result.status, 201);
  let item = result.body.case;
  const path = `/api/cases/${item.id}`;
  assert.equal(item.revision, 1); assert.equal(item.provenance, 'synthetic');
  const mutate = async (suffix, fields) => {
    const response = await post(path + suffix, { expectedRevision: item.revision, note, ...fields });
    assert.ok([200, 201].includes(response.status), JSON.stringify(response.body));
    item = response.body.case;
    return response.body;
  };
  await mutate('/context', { applicability: { funding: 'yes' }, policyBasis: { confirmed: true, description: 'Scenario uses the reviewed VA policy basis.', sourceIds: ['va-rfo'] } });
  const stale = await post(path + '/context', { expectedRevision: 1, note, owner: 'Stale editor' });
  assert.equal(stale.status, 409); assert.equal(stale.body.currentRevision, item.revision);
  await mutate('/records', { title: 'Contract records', owner: 'Records officer' });
  const recordId = item.records[0].id;
  await mutate(`/records/${recordId}`, { schedule: { authority: 'Synthetic test schedule', years: 6, trigger: 'final-payment', confirmed: true }, finalPaymentDate: '2018-01-01' });
  assert.equal(item.records[0].hold, 'unknown');
  await mutate(`/records/${recordId}/hold`, { status: 'active', reference: 'demo://hold-order' });
  const denied = await post(path + `/records/${recordId}/hold`, { expectedRevision: item.revision, note, status: 'none', reference: 'demo://review' });
  assert.equal(denied.status, 400);
  await mutate('/tasks', { findingId: `${item.id}:funding`, title: 'Obtain funds reference', owner: 'Contracting reviewer', dueDate: '2026-11-10' });
  const taskId = item.tasks[0].id;
  await mutate(`/tasks/${taskId}`, { status: 'done' });
  const guided = await post(path + '/agent', { intent: 'tasks' });
  assert.equal(guided.body.result[0].needsFollowUp, true);
  assert.equal(guided.body.trace[0].tool, 'list_follow_up_tasks');
  const added = await post(path + '/evidence', { kind: 'funding', title: 'Funding reference', locator: 'demo://funding' });
  const evidenceId = added.body.id;
  assert.equal((await post(path + '/verify-evidence', { evidenceId, note })).status, 200);
  item = (await (await fetch(base + '/api/cases')).json()).cases.find(c => c.id === item.id);
  await mutate(`/evidence/${evidenceId}`, { locator: 'demo://corrected-reference' });
  assert.equal(item.evidence[0].verified, false);
  const report = await (await fetch(base + path + '/report?asOf=2026-11-15')).json();
  assert.equal(report.records[0].retention.status, 'blocked');
  assert.equal(report.findings.find(f => f.id.endsWith(':funding')).status, 'needs-review');
  const queue = await (await fetch(base + '/api/tasks?asOf=2026-11-15')).json();
  assert.equal(queue.tasks[0].findingStatus, 'needs-review');
  const packet = await (await fetch(base + '/api/export')).json();
  assert.equal(packet.cases.find(c => c.id === item.id).revision, item.revision);
  assert.ok(packet.events.some(e => e.details.change?.command === 'record-hold' && e.details.change.reference === 'demo://hold-order'));
  assert.ok(packet.events.every(e => Number.isInteger(e.workspaceRevision)));
  assert.equal((await post(path + '/context', { note, owner: 'Missing revision' })).status, 400);
  assert.equal((await post(path + '/tasks', { expectedRevision: item.revision, note, findingId: 'DEMO-VA-001:funding', title: 'Cross-case', owner: 'Reviewer' })).status, 404);
});
