import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, rm, readFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { once } from 'node:events';
import { createApp } from '../src/server.mjs';

test('catalog screens share a snapshot and repeated writes commit once across restart', async t => {
  const directory = await mkdtemp(join(tmpdir(), 'compliance-catalog-'));
  const stateFile = join(directory, 'workspace.json');
  let server;
  let base;
  const start = async () => {
    server = await createApp({ stateFile });
    server.listen(0, '127.0.0.1'); await once(server, 'listening');
    base = `http://127.0.0.1:${server.address().port}`;
  };
  await start();
  t.after(async () => { await new Promise(r => server.close(r)); await rm(directory, { recursive: true, force: true }); });
  const get = async path => { const response = await fetch(base + path); return { status: response.status, body: await response.json() }; };
  const post = async (path, body, key) => {
    const response = await fetch(base + path, { method: 'POST', headers: { 'Content-Type': 'application/json', ...(key ? { 'Idempotency-Key': key } : {}) }, body: JSON.stringify(body) });
    return { status: response.status, body: await response.json() };
  };
  const dashboard = (await get('/api/dashboard?asOf=2026-11-15')).body;
  assert.equal(dashboard.counts.activeHolds, 1);
  const findings = (await get('/api/findings?status=needs-evidence&limit=1')).body;
  assert.equal(findings.items.length, 1);
  assert.equal(findings.pagination.total, dashboard.counts.evidenceGaps);
  assert.equal((await get('/api/records?hold=active')).body.items[0].retention.canDestroy, false);
  assert.equal((await get('/api/findings?status=unknown')).status, 400);
  assert.equal((await get('/api/findings?limit=1&limit=2')).status, 400);
  assert.equal((await get('/api/cases/missing')).status, 404);
  const path = '/api/cases/DEMO-VA-001';
  assert.equal((await get(path)).body.lastRunStale, null);
  await post(path + '/analyze', {}, 'analyze-1');
  assert.equal((await get(path)).body.lastRunStale, false);
  const edit = { title: 'Updated synthetic case', expectedRevision: 0, note: 'Reviewed this synthetic case title.' };
  const attempts = await Promise.all([post(path + '/context', edit, 'edit-1'), post(path + '/context', edit, 'edit-1')]);
  assert.equal(attempts[0].status, 200);
  assert.deepEqual(attempts[0], attempts[1]);
  const detail = (await get(path)).body;
  assert.equal(detail.case.revision, 1);
  assert.equal(detail.lastRunStale, true);
  assert.equal(detail.recentEvents.length, 2);
  assert.equal((await get('/api/findings?workspaceRevision=0')).status, 409);
  assert.equal((await post(path + '/context', { ...edit, title: 'Different request' }, 'edit-1')).status, 409);
  assert.equal((await post(path + '/context', edit, 'invalid key')).status, 400);
  assert.equal((await get('/api/activity?caseId=DEMO-VA-001&limit=1')).body.items[0].action, 'context');
  const create = { title: 'New synthetic workflow', owner: 'Demo owner', note: 'Creating a synthetic review case.' };
  const created = await post('/api/cases', create, 'create-1');
  assert.equal(created.status, 201);
  await new Promise(r => server.close(r));
  await start();
  assert.deepEqual(await post('/api/cases', { note: create.note, owner: create.owner, title: create.title }, 'create-1'), created, 'JSON key order must not change retry identity');
  assert.deepEqual(await post(path + '/context', edit, 'edit-1'), attempts[0], 'original result replays despite newer case revision');
  const workspace = (await get('/api/workspace')).body;
  assert.equal(workspace.cases.length, 4);
  assert.equal(workspace.events.length, 3);
  assert.equal('requests' in workspace, false);
  assert.equal('requests' in (await get('/api/export')).body, false);
  const saved = JSON.parse(await readFile(stateFile, 'utf8'));
  assert.equal(saved.requests.length, 3);
});
