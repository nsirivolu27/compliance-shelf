import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, rm, readFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { once } from 'node:events';
import { randomBytes } from 'node:crypto';
import { createApp } from '../../apps/records-contracting/src/server.mjs';
import { createDocumentsService } from '../documents.mjs';
import { createJobsService } from '../jobs.mjs';
import { createWorkerService } from '../worker.mjs';
import { createPoliciesService } from '../policies.mjs';
import { createAuditService } from '../audit.mjs';
import { createAgentService } from '../agent.mjs';
import { createGateway } from '../gateway.mjs';
import { digest } from '../common.mjs';

test('real HTTP services recover intake after a queue outage, preserve evidence review, and export scoped audit data', async t => {
  const directory = await mkdtemp(join(tmpdir(), 'compliance-services-'));
  const token = randomBytes(32).toString('hex'), servers = [];
  const listen = async (server, port = 0) => { servers.push(server); server.listen(port, '127.0.0.1'); await once(server, 'listening'); return `http://127.0.0.1:${server.address().port}`; };
  const close = async server => { if (server.stopBackground) await server.stopBackground(); if (server.listening) await new Promise(resolve => server.close(resolve)); };
  t.after(async () => { for (const server of [...servers].reverse()) await close(server); await rm(directory, { recursive: true, force: true }); });
  const workflowUrl = await listen(await createApp({ stateFile: join(directory, 'workspace.json'), internalToken: token }));
  let jobs = await createJobsService({ token, stateFile: join(directory, 'jobs.json') });
  const jobsUrl = await listen(jobs), jobPort = jobs.address().port;
  let docs = await createDocumentsService({ token, stateFile: join(directory, 'documents.json'), workflowUrl, jobsUrl, outboxInterval: 60000 });
  const documentsUrl = await listen(docs), docPort = docs.address().port;
  const policiesUrl = await listen(await createPoliciesService({ token }));
  const auditUrl = await listen(createAuditService({ token, workflowUrl, documentsUrl }));
  const agentUrl = await listen(createAgentService({ token, workflowUrl }));
  const worker = createWorkerService({ token, jobsUrl, documentsUrl, interval: 60000 });
  const workerUrl = await listen(worker);
  const gatewayUrl = await listen(createGateway({ token, urls: { workflow: workflowUrl, documents: documentsUrl, jobs: jobsUrl, policies: policiesUrl, audit: auditUrl, agent: agentUrl, worker: workerUrl } }));
  const request = async (path, { method = 'GET', body, key, base = gatewayUrl, internal = false, headers = {} } = {}) => {
    const response = await fetch(base + path, { method, headers: { ...(body ? { 'content-type': 'application/json' } : {}), ...(key ? { 'idempotency-key': key } : {}), ...(internal ? { 'x-platform-token': token } : {}), ...headers }, ...(body ? { body: JSON.stringify(body) } : {}) });
    return { status: response.status, body: await response.json(), requestId: response.headers.get('x-request-id') };
  };
  assert.equal((await request('/api/services')).body.status, 'ok');
  assert.equal((await request('/api/documents', { base: documentsUrl })).status, 401);
  assert.equal((await request('/api/workspace', { base: workflowUrl })).status, 401);
  assert.equal((await request('/internal/jobs/claim', { method: 'POST', body: {} })).status, 404);
  assert.equal((await request('/api/workspace', { headers: { Origin: 'https://untrusted.example' } })).status, 403);
  const html = await (await fetch(gatewayUrl)).text(); assert.match(html, /Compliance Shelf/);
  assert.equal((await request('/api/policies/far-4.803')).body.source.id, 'far-4.803');
  assert.equal((await request('/api/agent/tools')).body.tools.length, 8);
  await close(jobs);
  const input = { caseId: 'DEMO-VA-001', title: 'Synthetic funding source', filename: 'funds.txt', mediaType: 'text/plain', content: 'Synthetic certification.\r\nFunding reference for this demonstration.\r\n', note: 'Intake of a synthetic funding document.' };
  const received = await request('/api/documents', { method: 'POST', body: input, key: 'intake-1' });
  assert.equal(received.status, 202); assert.equal(received.body.document.dispatchPending, true);
  assert.ok(received.requestId);
  const doc = received.body.document;
  await close(docs);
  docs = await createDocumentsService({ token, stateFile: join(directory, 'documents.json'), workflowUrl, jobsUrl, outboxInterval: 60000 });
  await listen(docs, docPort);
  jobs = await createJobsService({ token, stateFile: join(directory, 'jobs.json') }); await listen(jobs, jobPort);
  await docs.pumpOutbox();
  const replay = await request('/api/documents', { method: 'POST', body: input, key: 'intake-1' });
  assert.equal(replay.body.document.id, doc.id);
  assert.equal((await request('/api/jobs')).body.pagination.total, 1);
  assert.equal((await request('/api/documents', { method: 'POST', body: { ...input, title: 'Changed' }, key: 'intake-1' })).status, 409);
  assert.equal((await request(`/api/documents/${doc.id}/evidence`, { method: 'POST', key: 'link-1', body: { kind: 'funding', expectedRevision: 0, note: 'Link this synthetic reference.' } })).status, 409);
  await worker.workOnce();
  assert.equal((await request(`/api/jobs/${doc.jobId}`)).body.job.status, 'succeeded');
  assert.equal('leaseToken' in (await request(`/api/jobs/${doc.jobId}`)).body.job, false);
  const spans = (await request(`/api/documents/${doc.id}/spans?q=funding`)).body;
  assert.equal(spans.sha256, digest(input.content.replace(/\r\n/g, '\n')));
  assert.ok(spans.items[0].text.includes('Funding reference'));
  const link = { kind: 'funding', expectedRevision: 0, note: 'Link this synthetic reference.' };
  const staleLink = await request(`/api/documents/${doc.id}/evidence`, { method: 'POST', key: 'link-stale', body: { ...link, expectedRevision: 99 } });
  assert.equal(staleLink.status, 409);
  assert.equal(staleLink.body.currentRevision, 0, 'revision conflicts must survive the document service and gateway');
  assert.equal((await request('/api/workspace')).body.events.length, 0, 'a rejected link adds no workflow event');
  const linked = await request(`/api/documents/${doc.id}/evidence`, { method: 'POST', key: 'link-1', body: link });
  assert.equal(linked.status, 201); assert.equal(linked.body.evidence.verified, false);
  assert.equal((await request(`/api/documents/${doc.id}/evidence`, { method: 'POST', key: 'link-1', body: link })).body.evidence.id, linked.body.evidence.id);
  assert.equal((await request(`/api/documents/${doc.id}/evidence`, { method: 'POST', key: 'link-1', body: { ...link, note: 'A different rationale for this link.' } })).status, 409);
  const verified = await request('/api/cases/DEMO-VA-001/verify-evidence', { method: 'POST', key: 'verify-1', body: { evidenceId: linked.body.evidence.id, expectedRevision: 1, note: 'Reviewed this synthetic funding source.' } });
  assert.equal(verified.status, 200);
  const report = (await request('/api/cases/DEMO-VA-001/analyze', { method: 'POST', body: {}, key: 'run-1' })).body;
  assert.equal(report.findings.find(f => f.id.endsWith(':funding')).status, 'evidence-present');
  assert.equal(report.records.find(r => r.id === 'REC-001').retention.status, 'blocked');
  const agent = await request('/api/cases/DEMO-VA-001/agent', { method: 'POST', body: { intent: 'retention' } });
  assert.equal(agent.body.mode, 'deterministic-guided-agent');
  const audit = (await request('/api/audit/cases/DEMO-VA-001')).body;
  assert.equal(audit.integrity.hash, digest(JSON.stringify(audit.packet)));
  assert.equal(audit.packet.documents.status, 'available');
  assert.equal(audit.packet.documents.documents[0].sha256, doc.sha256);
  assert.ok(audit.packet.events.every(e => e.caseId === 'DEMO-VA-001'));
  const saved = JSON.parse(await readFile(join(directory, 'workspace.json'), 'utf8'));
  assert.equal(saved.events.length, 3);
  await close(docs);
  assert.equal((await request('/api/services')).body.status, 'degraded');
  assert.equal((await request('/api/audit/cases/DEMO-VA-001')).body.packet.documents.status, 'unavailable');
  assert.equal((await request('/api/export')).status, 200);
});
